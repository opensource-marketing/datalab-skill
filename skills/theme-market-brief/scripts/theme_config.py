def resolve_theme(value):
    """사용자가 쓴 말을 테마 이름으로 바꾼다. 모르면 ValueError."""
    text = str(value or "").strip()
    # "의료 관광"·"야간 관광"·"K-컬처"처럼 띄어쓰기와 붙임표는 사람마다
    # 다르다. 별칭을 그만큼 늘리는 대신 지워서 맞춘다.
    납작 = text.replace(" ", "").replace("-", "").replace("·", "")
    found = (ALIASES.get(text) or ALIASES.get(text.lower())
             or ALIASES.get(납작) or ALIASES.get(납작.lower()))
    # "케이팝 관광"처럼 뒤에 "관광"을 붙여 말하는 것이 자연스럽다.
    # 별칭마다 "…관광" 짝을 두는 대신 꼬리를 벗겨 한 번 더 본다.
    if not found and 납작.endswith("관광") and len(납작) > 2:
        벗김 = 납작[:-2]
        found = ALIASES.get(벗김) or ALIASES.get(벗김.lower())
    if found:
        return found
    labels = ", ".join(f"{name}({THEMES[name]['label']})"
                       for name in theme_names())
    raise ValueError(f"모르는 테마입니다: {value}\n  쓸 수 있는 테마: {labels}")


def default_period(theme):
    """테마의 기본 기간. 테마마다 다르다.

    한류는 설문이라 연 단위이고, MICE는 직전 연도를 포함해야 값이 나온다.
    """
    return THEMES[theme]["default_period"]

